const std::span<const uint8_t> kPackets[] = {
    kPacket0, kPacket1, kPacket2, kPacket3, kPacket4, kPacket5, kPacket6};

struct DecodedPass {
  int64_t pts = kNoTimestamp;
  std::vector<float> samples;
};

bool Initialize(MediaCodecAudioDecoder* decoder) {
  AudioConfig config;
  config.codec = AudioCodec::kOpus;
  config.codec_name = "opus";
  config.sample_rate = 48000;
  config.channels = 1;
  config.extradata.assign(std::begin(kOpusHead), std::end(kOpusHead));
  std::string error;
  const bool ok = decoder->Initialize(config, {48000, 1}, &error);
  EXPECT_TRUE(ok);
  EXPECT_EQ(error, std::string());
  return ok;
}

DecodedPass DecodePass(MediaCodecAudioDecoder* decoder, int64_t first_pts) {
  DecodedPass result;
  auto output = [&](const std::shared_ptr<AudioBuffer>& buffer) {
    if (result.pts == kNoTimestamp) {
      result.pts = buffer->pts;
    }
    result.samples.insert(result.samples.end(), buffer->samples.begin(),
                          buffer->samples.end());
  };
  for (const auto& data : kPackets) {
    EncodedPacket packet;
    packet.buffer = PacketBuffer::Copy(data.data(), data.size());
    packet.pts = packet.dts = first_pts;
    packet.duration = 20000;
    EXPECT_TRUE(decoder->Decode(packet, output));
    first_pts += packet.duration;
  }
  EXPECT_TRUE(decoder->Decode(*EncodedPacket::CreateEndOfStream(0), output));
  return result;
}

// NOLINTNEXTLINE(bugprone-throwing-static-initialization)
TEST(MediaCodecAudioDecoder, OpusLoopKeepsInitialSamplesAndTimeline) {
  MediaCodecAudioDecoder decoder;
  if (!Initialize(&decoder)) {
    return;
  }
  // AudioRenderer flushes the initial generation before decoding packets.
  decoder.Flush();
  const auto first = DecodePass(&decoder, -6500);
  EXPECT_EQ(first.pts, 0);
  EXPECT_EQ(first.samples.size(), std::size(kPackets) * 960 - 312);
  // Loop packets carry an offset on the continuous player timeline.
  // Draining above already flushed the decoder, as in AudioRenderer.
  decoder.Restart();
  const auto second = DecodePass(&decoder, 993500);
  EXPECT_EQ(second.pts, 1000000);
  EXPECT_EQ(second.samples.size(), first.samples.size());
  EXPECT_TRUE(second.samples == first.samples);
}

// NOLINTNEXTLINE(bugprone-throwing-static-initialization)
TEST(MediaCodecAudioDecoder, OpusMidstreamSeekKeepsPreroll) {
  MediaCodecAudioDecoder decoder;
  if (!Initialize(&decoder)) {
    return;
  }
  DecodePass(&decoder, -6500);
  decoder.Flush();
  const auto seek = DecodePass(&decoder, 1000000);
  EXPECT_EQ(seek.pts, 1080000);
  EXPECT_EQ(seek.samples.size(), std::size(kPackets) * 960 - 3840);
}

// NOLINTNEXTLINE(bugprone-throwing-static-initialization)
TEST(MediaCodecAudioDecoder, OpusSeekToBeginningKeepsInitialSamples) {
  MediaCodecAudioDecoder decoder;
  if (!Initialize(&decoder)) {
    return;
  }
  const auto first = DecodePass(&decoder, -6500);
  decoder.Flush();
  const auto seek = DecodePass(&decoder, -6500);
  EXPECT_EQ(seek.pts, 0);
  EXPECT_TRUE(seek.samples == first.samples);
}

