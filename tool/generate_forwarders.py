#!/usr/bin/env python3
"""Generates flutter/darwin/Classes/core/*.{cc,mm}, which compile the core library sources.

CocoaPods only compiles files inside the pod directory, so each core source
gets a one-line forwarder. Run after adding or removing core sources.
Backends for other platforms are left out.
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "core" / "src"
darwin_backends = {"apple", "ffmpeg"}
sources = sorted(
    path
    for path in [*src.rglob("*.cc"), *src.rglob("*.mm")]
    if path.relative_to(src).parts[0] != "backends"
    or path.relative_to(src).parts[1] in darwin_backends
)
out = root / "flutter" / "darwin" / "Classes" / "core"
out.mkdir(parents=True, exist_ok=True)
for old in [*out.glob("*.cc"), *out.glob("*.mm")]:
    old.unlink()
for source in sources:
    relative = source.relative_to(root)
    name = "_".join(source.relative_to(src).parts)
    (out / name).write_text(
        "// Generated by tool/generate_forwarders.py. Do not edit.\n"
        f'#include "../../../../{relative.as_posix()}"\n'
    )
print(f"wrote {len(sources)} forwarders to {out.relative_to(root)}")
