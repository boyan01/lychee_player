#!/usr/bin/env python3
"""Generates macos/Classes/core/*.cc, which compile the core library sources.

CocoaPods only compiles files inside the pod directory, so each core source
gets a one-line forwarder. Run after adding or removing core sources.
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
sources = sorted((root / "core" / "src").rglob("*.cc"))
out = root / "macos" / "Classes" / "core"
out.mkdir(parents=True, exist_ok=True)
for old in out.glob("*.cc"):
    old.unlink()
for source in sources:
    relative = source.relative_to(root)
    name = "_".join(source.relative_to(root / "core" / "src").parts)
    (out / name).write_text(
        "// Generated by tool/generate_forwarders.py. Do not edit.\n"
        f'#include "../../../{relative.as_posix()}"\n'
    )
print(f"wrote {len(sources)} forwarders to {out.relative_to(root)}")
